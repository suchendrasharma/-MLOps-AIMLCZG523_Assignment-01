// Minimal inline markup: **bold**, `code`, plain text.
function runs(text, base = {}) {
  return String(text).split(/(\*\*[^*]+\*\*|`[^`]+`)/).filter(Boolean).map((part) => {
    if (part.startsWith("**")) return new TextRun({ ...base, text: part.slice(2, -2), bold: true });
    if (part.startsWith("`")) {
      return new TextRun({ ...base, text: part.slice(1, -1), font: MONO, size: 19, color: "7A2E0E" });
    }
    return new TextRun({ ...base, text: part });
  });
}
