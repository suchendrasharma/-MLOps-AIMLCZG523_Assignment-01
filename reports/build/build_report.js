function code(lines) {
  return lines.map((ln, i) => new Paragraph({
    children: [new TextRun({ text: ln || " ", font: MONO, size: 17, color: "1F1F1F" })],
    shading: { type: ShadingType.CLEAR, fill: "F3F2EE", color: "auto" },
    spacing: { after: i === lines.length - 1 ? 160 : 0, line: 240 },
    indent: { left: 120, right: 120 },
  }));
}

function callout(text) {
  return new Paragraph({
    children: runs(text, { color: INK }),
    shading: { type: ShadingType.CLEAR, fill: TINT, color: "auto" },
    border: { left: { style: BorderStyle.SINGLE, size: 18, color: BLUE, space: 8 } },
    spacing: { before: 60, after: 160, line: 264 }, indent: { left: 160, right: 120 },
  });
}

